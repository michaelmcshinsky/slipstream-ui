/**
 * Worker entrypoint.
 *
 * Wraps the OpenNext-generated handler with the anonymous HTML cache in
 * `lib/edge-cache.ts`. The cache exists because the Workers Free plan caps each
 * invocation at 10 ms of CPU and rendering a page can exceed that
 * (`exceededCpu` -> HTTP 503, error 1102).
 *
 * Every docs page is public, so nothing beyond the module's `/api` and
 * `/_next` bypasses is excluded. The locale cookie is sensitive: the App Router
 * reads it during SSR, so a request carrying it must never be served another
 * reader's cached HTML.
 *
 * Keep this file a thin adapter; the decision logic lives in
 * `lib/edge-cache.ts`.
 */

// @ts-expect-error - generated by `opennextjs-cloudflare build`
import openNext from "./.open-next/worker.js";

import { edgeCacheFetch } from "./lib/edge-cache";

const worker = {
  fetch(
    request: Request,
    env: unknown,
    ctx: { waitUntil(promise: Promise<unknown>): void },
  ): Promise<Response> {
    return edgeCacheFetch(request, ctx, () => openNext.fetch(request, env, ctx), {
      site: "slipstream-ui-docs",
      // /api, /_next, /auth, /keystatic and /embed are always bypassed.
      bypassPrefixes: [],
      // `lib/i18n-server.ts` (LOCALE_COOKIE): SSR renders the reader's locale.
      sensitiveCookies: ["slipstream-locale"],
      // Next marks every docs page `private, no-cache, no-store` because the
      // App Router reads the locale cookie. Requests carrying that cookie are
      // already bypassed above, so store the anonymous renders anyway.
      allowPrivateResponses: true,
      ttlSeconds: 60 * 60 * 6,
    });
  },
};

export default worker;
