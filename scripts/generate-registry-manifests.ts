#!/usr/bin/env node
/**
 * Inlines the manifest-derived docs sections (anti-patterns, composition
 * rules, related components, dependencies, design intent, content
 * guidelines) into a TypeScript module so component pages render them in
 * the server HTML instead of fetching /registry/<id>.json after hydration.
 *
 * Source is apps/docs/public/registry/*.json — the same payloads the client
 * fetch used, so docs and validate_usage stay in lockstep. Output is
 * committed; regenerate with `pnpm generate:registry-manifests` (also runs
 * in the docs build after generate-registry).
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const REGISTRY_DIR = path.join(ROOT, 'apps', 'docs', 'public', 'registry');
const OUT_PATH = path.join(ROOT, 'apps', 'docs', 'lib', 'registry-manifests.generated.ts');

const FIELDS = [
  'antiPatterns',
  'compositionRules',
  'relatedComponents',
  'dependencies',
  'registryDependencies',
  'designIntent',
  'contentGuidelines',
] as const;

type Slice = Partial<Record<(typeof FIELDS)[number], unknown>>;

const entries: string[] = [];
for (const file of fs.readdirSync(REGISTRY_DIR).sort()) {
  if (!file.endsWith('.json') || file === 'all.json') continue;
  const id = file.replace(/\.json$/, '');
  const manifest = JSON.parse(
    fs.readFileSync(path.join(REGISTRY_DIR, file), 'utf8'),
  ) as Record<string, unknown>;
  const slice: Slice = {};
  for (const field of FIELDS) {
    if (manifest[field] !== undefined) slice[field] = manifest[field];
  }
  // Some manifests nest string arrays inside example lists (e.g. an icon
  // pair ["−", "+"]). React rendered them concatenated; flatten to a string
  // so the generated type stays string[].
  const guidelines = slice.contentGuidelines as
    | { goodExamples?: unknown[]; badExamples?: unknown[] }[]
    | undefined;
  for (const group of guidelines ?? []) {
    for (const key of ['goodExamples', 'badExamples'] as const) {
      const list = group[key];
      if (Array.isArray(list)) {
        group[key] = list.map((item) => (Array.isArray(item) ? item.join('') : item));
      }
    }
  }
  if (Object.keys(slice).length === 0) continue;
  entries.push(`  ${JSON.stringify(id)}: ${JSON.stringify(slice)},`);
}

const out = `// GENERATED by scripts/generate-registry-manifests.ts — do not edit.
// Manifest-derived docs sections inlined so component pages render them in
// the server HTML (the docs deploy target is a Cloudflare Worker, where
// /registry/*.json is a runtime fetch). Regenerate after pnpm generate:registry.
export type RegistryManifestSlice = {
  antiPatterns?: { title?: string; explanation?: string; example?: string }[];
  compositionRules?: { component?: string; relationship?: string; example?: string }[];
  relatedComponents?: string[];
  dependencies?: string[];
  registryDependencies?: string[];
  designIntent?: string;
  contentGuidelines?: {
    contentType?: string;
    guidelines?: string[];
    goodExamples?: string[];
    badExamples?: string[];
  }[];
};

export const REGISTRY_MANIFESTS: Record<string, RegistryManifestSlice> = {
${entries.join('\n')}
};

/** Look up the inlined manifest slice for a registry id (e.g. "button"). */
export function getRegistryManifest(id: string): RegistryManifestSlice | undefined {
  return REGISTRY_MANIFESTS[id];
}
`;

fs.writeFileSync(OUT_PATH, out);
console.log(
  `Registry manifests generated: ${entries.length} components -> ${path.relative(ROOT, OUT_PATH)}`,
);
