#!/usr/bin/env node
/**
 * Inlines article markdown into a TypeScript module so lib/articles.ts never
 * touches the filesystem at runtime — the docs deploy target is a Cloudflare
 * Worker, where content/articles/*.md does not exist and module-load fs reads
 * 500 every /articles route.
 *
 * Output is committed; regenerate with `pnpm generate:article-content` (also
 * runs in the docs build). articles.test.ts fails if the generated module
 * drifts from the .md files on disk.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const ARTICLES_DIR = path.join(ROOT, 'apps', 'docs', 'content', 'articles');
const META_PATH = path.join(ROOT, 'apps', 'docs', 'content', 'articles.json');
const OUT_PATH = path.join(ROOT, 'apps', 'docs', 'lib', 'article-content.generated.ts');

const meta = JSON.parse(fs.readFileSync(META_PATH, 'utf8')) as { slug: string; file: string }[];

const entries = meta
  .map(({ slug, file }) => {
    const filePath = path.join(ARTICLES_DIR, file);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Article file missing for "${slug}": ${filePath}`);
    }
    const content = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n');
    return `  ${JSON.stringify(slug)}: ${JSON.stringify(content)},`;
  })
  .join('\n');

const out = `// GENERATED by scripts/generate-article-content.ts — do not edit.
// Article markdown inlined so lib/articles.ts never reads the filesystem at
// runtime (the docs deploy target is a Cloudflare Worker).
export const ARTICLE_CONTENT: Record<string, string> = {
${entries}
};
`;

fs.writeFileSync(OUT_PATH, out);
console.log(
  `Article content generated: ${meta.length} articles -> ${path.relative(ROOT, OUT_PATH)}`,
);
