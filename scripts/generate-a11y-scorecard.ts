#!/usr/bin/env node
/**
 * Snapshots the component accessibility scorecard into a TypeScript module so
 * the scorecard page never touches the filesystem at runtime — the docs
 * deploy target is a Cloudflare Worker with no packages/ directory, where the
 * fs-based builder 500s the route.
 *
 * Output is committed; regenerate with `pnpm generate:a11y-scorecard` (also
 * runs in the docs build). a11y-scorecard.test.ts fails if it drifts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { buildAccessibilityScorecard } from '../apps/docs/lib/a11y-scorecard';

const ROOT = path.resolve(__dirname, '..');
const OUT_PATH = path.join(ROOT, 'apps', 'docs', 'lib', 'a11y-scorecard.generated.ts');

const data = buildAccessibilityScorecard();

const out = `// GENERATED by scripts/generate-a11y-scorecard.ts — do not edit.
// Snapshot of buildAccessibilityScorecard() so the page renders on the
// Cloudflare Worker, which has no filesystem access to packages/.
import type { AccessibilityRow, AccessibilitySummary } from './a11y-scorecard';

export const ACCESSIBILITY_SCORECARD: { rows: AccessibilityRow[]; summary: AccessibilitySummary } =
  ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(OUT_PATH, out);
console.log(
  `Accessibility scorecard generated: ${data.rows.length} rows -> ${path.relative(ROOT, OUT_PATH)}`,
);
