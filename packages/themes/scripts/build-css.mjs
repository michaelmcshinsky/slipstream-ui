/**
 * Emits the default light/dark theme variables as a stylesheet so consumers
 * can use Slipstream without calling createTheme() at runtime.
 *
 *   import '@slipstream-ui/themes/styles.css'
 *
 * Runtime theme switching still works: createTheme()/themeToCssVariables()
 * can overwrite these variables on :root or a scoped container.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const { defaultTheme, darkTheme, themeToCssVariables } = await import(
  pathToFileURL(resolve(root, 'dist/index.mjs')).href
)

const css = `/*
 * Slipstream UI default theme variables.
 * Generated by packages/themes/scripts/build-css.mjs - do not edit by hand.
 */
:root {
${themeToCssVariables(defaultTheme)}
}

.dark,
[data-theme='dark'] {
${themeToCssVariables(darkTheme)}
}
`

mkdirSync(resolve(root, 'dist'), { recursive: true })
writeFileSync(resolve(root, 'dist/styles.css'), css)
console.log('Wrote dist/styles.css')
